def steps(device: str, link: str) -> str:
    return _STEPS.format(device=device, link=link)


def status(access: Access, link: str) -> str:
    if access.active:
        head = "● <b>Доступ активен</b>"
        until = f"до <b>{date_msk(access.expire)}</b>" if access.expire else "без срока"
    else:
        head = "○ <b>Доступ закончился</b>"
        until = f"был до {date_msk(access.expire)}" if access.expire else ""
    traffic = f"{gb(access.used_bytes)} из {gb(access.limit_bytes)} ГБ" if access.limit_bytes else f"{gb(access.used_bytes)} ГБ"
    return (
        f"{head}\n"
        "━━━━━━━━━━━━━━\n"
        f"Срок: {until}\n"
        f"Трафик: {traffic}\n"
        f"Устройств: до {DEVICES}\n\n"
        f"Ссылка подписки:\n<code>{link}</code>"
    )


